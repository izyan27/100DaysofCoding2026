public class day005 {
    public static void main(String[] args) {

        // byte: 8 bit, untuk bilangan bulat kecil
        byte semester = 2;

        // short: 16 bit, untuk bilangan bulat yang lebih besar
        short jumlahSKS = 24;

        // int: 32 bit, untuk bilangan bulat yang sering digunakan
        int uangSaku = 1500000;

        // long: 64 bit, untuk angka yang sangat besar
        long jumlahPendudukIndonesia = 280000000L;

        // Menampilkan semua nilai ke layar
        System.out.println("Semester: " + semester);
        System.out.println("Jumlah SKS: " + jumlahSKS);
        System.out.println("Uang Saku: Rp " + uangSaku);
        System.out.println("Jumlah Penduduk Indonesia: " + jumlahPendudukIndonesia);
    }
}
